from __future__ import annotations

import re
from pathlib import Path
from typing import Any, TypeIs

import yaml
from pydantic import BaseModel, ConfigDict, ValidationError, field_validator

# Validate both renderings' consumed keys against the declaration: every key either rendering
# consumes appears here, and mint keys ride the externally managed k8s Secret.
DECLARED_KEY = re.compile(r"^[A-Z][A-Z0-9_]*$")

# Count a brace hole as consumed when an odd number of dollars precedes it; even runs are
# $$-escaped literals.
COMPOSE_HOLE = re.compile(r"(\$+)\{([A-Z][A-Z0-9_]*)(?::[^{}]*)?\}")


class SecretKey(BaseModel):
    model_config = ConfigDict(extra="forbid")

    description: str
    mint: bool = False

    @field_validator("description")
    @classmethod
    def _require_description(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("every declared key needs a one-line description")
        return value


def load_declaration(path: Path) -> dict[str, SecretKey]:
    if not path.is_file():
        raise RuntimeError(f"{path.as_posix()}: the secrets declaration file does not exist")

    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not _is_mapping(document) or not document:
        raise RuntimeError(f"{path.as_posix()}: the secrets declaration is a non-empty KEY: description mapping")

    declared: dict[str, SecretKey] = {}
    for name, spec in document.items():
        if not isinstance(name, str) or not DECLARED_KEY.match(name):
            raise RuntimeError(f"{path.as_posix()}: {name!r} is not an ALL_CAPS key")
        if isinstance(spec, str):
            spec = {"description": spec}
        try:
            declared[name] = SecretKey.model_validate(spec)
        except ValidationError as error:
            raise RuntimeError(f"{path.as_posix()}: key {name} rejected: {error}") from error

    return declared


def compose_consumed_keys(artifact_text: str) -> set[str]:
    consumed: set[str] = set()
    for match in COMPOSE_HOLE.finditer(artifact_text):
        if len(match.group(1)) % 2 == 1:
            consumed.add(match.group(2))

    return consumed


def k8s_consumed_keys(manifest_text: str, secret_name: str) -> set[str]:
    consumed: set[str] = set()
    for block in re.split(r"(?m)^---$\n", manifest_text):
        if block.strip():
            _collect_secret_keys(yaml.safe_load(block), secret_name, consumed)

    return consumed


def validate_consumed(consumed: set[str], declared: dict[str, SecretKey], rendering: str, source: str) -> None:
    undeclared = sorted(consumed - declared.keys())
    if undeclared:
        raise RuntimeError(
            f"{source}: the {rendering} rendering consumes keys missing from the secrets declaration: "
            + ", ".join(undeclared)
        )


def mint_text(declared: dict[str, SecretKey]) -> str:
    return "# Generated by generate-score from the secrets declaration\n" + "".join(
        f"{name}\n" for name in sorted(name for name, key in declared.items() if key.mint)
    )


def _collect_secret_keys(node: Any, secret_name: str, consumed: set[str]) -> None:
    if _is_mapping(node):
        reference = node.get("secretKeyRef")
        if _is_mapping(reference) and reference.get("name") == secret_name:
            key = reference.get("key")
            if isinstance(key, str):
                consumed.add(key)

        for value in node.values():
            _collect_secret_keys(value, secret_name, consumed)

    elif _is_list(node):
        for item in node:
            _collect_secret_keys(item, secret_name, consumed)


def _is_mapping(node: Any) -> TypeIs[dict[Any, Any]]:
    return isinstance(node, dict)


def _is_list(node: Any) -> TypeIs[list[Any]]:
    return isinstance(node, list)
